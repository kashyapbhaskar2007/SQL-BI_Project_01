-- ROW COUNT CHECK
SELECT 'customers' AS table_name, COUNT(*) AS row_count FROM CUSTOMER_DATA
UNION ALL
SELECT 'orders', COUNT(*) FROM ORDERS
UNION ALL
SELECT 'order_items', COUNT(*) FROM ORDER_ITEMS
UNION ALL
SELECT 'order_payments', COUNT(*) FROM ORDER_PAYMENTS
UNION ALL
SELECT 'order_reviews', COUNT(*) FROM ORDER_REVIEWS
UNION ALL
SELECT 'products', COUNT(*) FROM ORDER_PAYMENTS
UNION ALL
SELECT 'sellers', COUNT(*) FROM SELLERS
UNION ALL
SELECT 'category_translation', COUNT(*) FROM CATEGORY_TRANSLATION;



-- NULL CHECK FOR NECESSARY COLUMNS
SELECT 
 COUNT(*) AS total_orders,
 COUNT(*) FILTER (WHERE order_id IS NULL) AS null_order_id,
 COUNT(*) FILTER (WHERE customer_id IS NULL) AS null_customer_id,
 COUNT(*) FILTER (WHERE order_status IS NULL) AS null_status,
 COUNT(*) FILTER (WHERE order_purchase_timestamp IS NULL) AS null_purchase_ts,
 COUNT(*) FILTER (WHERE order_delivered_customer_date IS NULL) AS null_delivered_date
FROM ORDERS;

SELECT 
 COUNT(*) AS TOTAL_PAYMENTS,
 COUNT(*) FILTER (WHERE ORDER_ID IS NULL) AS NULL_ORDER_ID,
 COUNT(*) FILTER (WHERE PAYMENT_TYPE  IS NULL) AS NULL_PAYMENT_TYPE
FROM ORDER_PAYMENTS;

SELECT 
    COUNT(*) AS total_items,
    COUNT(*) FILTER (WHERE order_id IS NULL) AS null_order_id,
    COUNT(*) FILTER (WHERE product_id IS NULL) AS null_product_id,
    COUNT(*) FILTER (WHERE seller_id IS NULL) AS null_seller_id,
    COUNT(*) FILTER (WHERE price IS NULL) AS null_price,
    COUNT(*) FILTER (WHERE freight_value IS NULL) AS null_freight
FROM ORDER_ITEMS;

SELECT 
    COUNT(*) AS total_reviews,
    COUNT(*) FILTER (WHERE review_id IS NULL) AS null_review_id,
    COUNT(*) FILTER (WHERE order_id IS NULL) AS null_order_id,
    COUNT(*) FILTER (WHERE review_score IS NULL) AS null_score
FROM ORDER_REVIEWS;

SELECT 
 COUNT(*) AS TOTAL_PRODUCTS,
 COUNT(*) FILTER (WHERE PRODUCT_ID IS NULL ) AS NULL_PRODUCT_ID,
 COUNT(*) FILTER (WHERE PRODUCT_CATEGORY_NAME IS NULL) AS NULL_CATEGORY
 FROM PRODUCTS;



 -- PRIMARY KEY UNIQUENESS CHECK
SELECT ORDER_ID, COUNT(*) 
FROM ORDERS
GROUP BY ORDER_ID
HAVING COUNT(*)>1;

SELECT CUSTOMER_ID, COUNT(*) 
FROM CUSTOMER_DATA 
GROUP BY customer_id 
HAVING COUNT(*) > 1;

SELECT PRODUCT_ID, COUNT(*) 
FROM PRODUCTS
GROUP BY PRODUCT_ID 
HAVING COUNT(*) > 1;

SELECT REVIEW_ID, COUNT(*) 
FROM ORDER_REVIEWS
GROUP BY REVIEW_ID 
HAVING COUNT(*) > 1;

SELECT SELLER_ID, COUNT(*) 
FROM SELLERS 
GROUP BY SELLER_ID 
HAVING COUNT(*) > 1;

SELECT ORDER_ID, ORDER_ITEM_ID, COUNT(*) 
FROM ORDER_ITEMS 
GROUP BY ORDER_ID, ORDER_ITEM_ID 
HAVING COUNT(*) > 1;


-- VALUE CHECKS

SELECT 
REVIEW_SCORE, 
COUNT(*)
FROM ORDER_REVIEWS
GROUP BY REVIEW_SCORE
ORDER BY REVIEW_SCORE DESC;

SELECT PRICE, PRODUCT_CATEGORY_NAME, COUNT(*)
FROM ORDER_ITEMS OI
LEFT JOIN PRODUCTS P
ON OI.PRODUCT_ID =P.PRODUCT_ID 
GROUP BY PRODUCT_CATEGORY_NAME,PRICE
HAVING PRICE < 0;

SELECT PAYMENT_VALUE, COUNT(*)
FROM ORDER_PAYMENTS
GROUP BY PAYMENT_VALUE
HAVING PAYMENT_VALUE  < 0;

SELECT order_status, COUNT(*) 
FROM ORDERS 
GROUP BY order_status 
ORDER BY COUNT(*) DESC;

SELECT payment_type, COUNT(*) 
FROM ORDER_PAYMENTS 
GROUP BY payment_type 
ORDER BY COUNT(*) DESC;


-- DATE CHECKS

SELECT COUNT(*) AS ERRORS 
FROM ORDERS 
WHERE ORDER_PURCHASE_TIMESTAMP > ORDER_APPROVED_AT;

SELECT COUNT(*) AS invalid_carrier_date
FROM ORDERS
WHERE order_delivered_carrier_date < order_approved_at;

SELECT COUNT(*) AS invalid_customer_delivery
FROM ORDERS
WHERE order_delivered_customer_date < order_delivered_carrier_date;

SELECT COUNT(*) AS invalid_estimated
FROM ORDERS
WHERE order_estimated_delivery_date < order_purchase_timestamp;

